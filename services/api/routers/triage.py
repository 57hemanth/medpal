"""Triage and booking endpoints.

The API is stateless: run state lives in the checkpointer, keyed by thread id."""

import uuid
from typing import Annotated, Any, Literal

from fastapi import APIRouter, Depends, HTTPException, Request, status
from langgraph.types import Command
from pydantic import BaseModel, Field

from services.api.deps import auth_ctx
from services.api.tracing import traced
from services.platform.auth import AuthContext

router = APIRouter(prefix="/triage", tags=["triage"])

Auth = Annotated[AuthContext, Depends(auth_ctx)]


class TriageIn(BaseModel):
    text: str = Field(min_length=3, max_length=2000)


class ResumeIn(BaseModel):
    """Answer the step the run is paused at: the safety screen, or the slot choice."""

    safety_answers: dict[str, bool] | None = None
    answer: str | None = Field(default=None, max_length=2000)  # reply to a clarifying question
    slot_id: str | None = None
    # Generated by the client per booking attempt; a retry reuses it.
    idempotency_key: str | None = Field(default=None, min_length=8, max_length=128)


class TriageOut(BaseModel):
    thread_id: str
    status: Literal[
        "awaiting_safety_check",
        "awaiting_clarification",
        "awaiting_choice",
        "booked",
        "emergency",
        "front_desk",
    ]
    reply: str | None = None
    candidates: list[dict[str, Any]] | None = None
    safety_questions: list[dict[str, str]] | None = None
    booking_id: str | None = None
    handoff_ticket_id: str | None = None
    ruleset_version: str | None = None
    ruleset_status: str | None = None
    specialty: str | None = None
    alternative_specialty: str | None = None  # also suitable; shown, never booked automatically
    specialty_source: Literal["rules", "model"] | None = None
    confidence: float | None = None


def _to_out(thread_id: str, out: dict[str, Any]) -> TriageOut:
    if out.get("__interrupt__"):
        value = out["__interrupt__"][0].value
        if value.get("type") == "clarify":
            return TriageOut(
                thread_id=thread_id,
                status="awaiting_clarification",
                reply=value["question"],
                ruleset_version=out.get("ruleset_version"),
                ruleset_status=out.get("ruleset_status"),
            )
        if value.get("type") == "safety_check":
            return TriageOut(
                thread_id=thread_id,
                status="awaiting_safety_check",
                reply="Before we book, please answer a few quick safety questions.",
                safety_questions=value["questions"],
                ruleset_version=out.get("ruleset_version"),
                ruleset_status=out.get("ruleset_status"),
            )
        return TriageOut(
            thread_id=thread_id,
            status="awaiting_choice",
            reply="Please pick one of these appointments.",
            candidates=value["candidates"],
            ruleset_version=out.get("ruleset_version"),
            ruleset_status=out.get("ruleset_status"),
            specialty=out.get("specialty"),
            alternative_specialty=out.get("alternative_specialty"),
            specialty_source="model" if out.get("specialty_rule_id") == "model" else "rules",
            confidence=out.get("confidence"),
        )
    return TriageOut(
        thread_id=thread_id,
        status=out["outcome"],
        reply=out.get("reply"),
        booking_id=out.get("booking_id"),
        handoff_ticket_id=out.get("handoff_ticket_id"),
        ruleset_version=out.get("ruleset_version"),
        ruleset_status=out.get("ruleset_status"),
        specialty=out.get("specialty"),
        confidence=out.get("confidence"),
    )


def _config(thread_id: str, callbacks: list[Any] | None = None) -> dict[str, Any]:
    config: dict[str, Any] = {"configurable": {"thread_id": thread_id}}
    if callbacks:
        config["callbacks"] = callbacks
    return config


@router.post("", response_model=TriageOut)
async def start_triage(body: TriageIn, request: Request, auth: Auth) -> TriageOut:
    if auth["role"] != "patient":
        # Caregiver and desk booking-on-behalf need the consent service (not built yet).
        raise HTTPException(
            status.HTTP_403_FORBIDDEN, "booking on behalf of another patient is not available yet"
        )
    thread_id = str(uuid.uuid4())
    async with traced(request, "triage", thread_id) as callbacks:
        out = await request.app.state.triage_graph.ainvoke(
            {"auth": auth, "intake_text": body.text}, _config(thread_id, callbacks)
        )
    return _to_out(thread_id, out)


@router.post("/{thread_id}/resume", response_model=TriageOut)
async def resume_triage(thread_id: str, body: ResumeIn, request: Request, auth: Auth) -> TriageOut:
    graph = request.app.state.triage_graph
    snapshot = await graph.aget_state(_config(thread_id))
    owner = (snapshot.values or {}).get("auth", {}).get("user_id")
    if owner is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "unknown thread")
    if owner != auth["user_id"]:
        # A thread id is not an authorisation (threat model: elevation of privilege).
        raise HTTPException(status.HTTP_403_FORBIDDEN, "not your thread")
    if not snapshot.next:
        raise HTTPException(status.HTTP_409_CONFLICT, "this triage run has already finished")
    async with traced(request, "triage", thread_id) as callbacks:
        out = await graph.ainvoke(
            Command(resume=body.model_dump(exclude_none=True)), _config(thread_id, callbacks)
        )
    return _to_out(thread_id, out)
